DO $$
DECLARE
    nome_tabela text;
BEGIN
    FOREACH nome_tabela IN ARRAY ARRAY[
        'log_integracao_sap',
        'entrada_produto_lancamento',
        'entrada_produto_item',
        'entrada_produto_pesagem'
    ]
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_atualizado_em ON homologacao.%I', nome_tabela, nome_tabela);
        EXECUTE format(
            'CREATE TRIGGER trg_%I_atualizado_em
             BEFORE UPDATE ON homologacao.%I
             FOR EACH ROW
             EXECUTE FUNCTION homologacao.fn_definir_atualizado_em()',
            nome_tabela,
            nome_tabela
        );

        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_log_alteracao_cadastral ON homologacao.%I', nome_tabela, nome_tabela);
        EXECUTE format(
            'CREATE TRIGGER trg_%I_log_alteracao_cadastral
             AFTER INSERT OR UPDATE OR DELETE ON homologacao.%I
             FOR EACH ROW
             EXECUTE FUNCTION homologacao.fn_registrar_log_alteracao_cadastral()',
            nome_tabela,
            nome_tabela
        );
    END LOOP;
END $$;

