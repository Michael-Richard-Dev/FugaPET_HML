-- Criado por, atualizado por e excluído por apontam para usuario(codigo)
-- ============================================================

DO $$
DECLARE
    r record;
    coluna_criado text;
    coluna_atualizado text;
    coluna_excluido text;
    nome_constraint text;
BEGIN
    FOR r IN
        SELECT *
        FROM (
            VALUES
                ('setor', 'setor'),
                ('cargo', 'cargo'),
                ('usuario', 'usuario'),
                ('perfil_acesso', 'perfil_acesso'),
                ('permissao', 'permissao'),
                ('perfil_permissao', 'perfil_permissao'),
                ('usuario_perfil', 'usuario_perfil'),
                ('usuario_setor', 'usuario_setor'),
                ('tipo_tara', 'tipo_tara'),
                ('balanca', 'balanca'),
                ('tara', 'tara'),
                ('modelo_etiqueta', 'modelo_etiqueta'),
                ('etiqueta', 'etiqueta'),
                ('campo_etiqueta', 'campo_etiqueta'),
                ('mapeamento_campo_etiqueta', 'mapeamento_campo_etiqueta'),
                ('produto_referencia', 'produto_referencia'),
                ('produto_etiqueta', 'produto_etiqueta'),
                ('norma_embalagem', 'norma_embalagem'),
                ('configuracao_geral', 'configuracao_geral'),
                ('parametro_operacao', 'parametro_operacao'),
                ('log_alteracao_cadastral', 'log_alteracao_cadastral'),
                ('auditoria_acao_usuario', 'auditoria_acao_usuario'),
                ('sap_servico_integracao', 'sap_servico_integracao'),
                ('sap_sincronizacao_execucao', 'sap_sincronizacao_execucao'),
                ('sap_payload_recebido', 'sap_payload_recebido'),
                ('sap_centro', 'sap_centro'),
                ('sap_deposito', 'sap_deposito'),
                ('sap_unidade_medida', 'sap_unidade_medida'),
                ('sap_produto', 'sap_produto'),
                ('sap_lote', 'sap_lote'),
                ('sap_fornecedor', 'sap_fornecedor'),
                ('sap_pedido_compra', 'sap_pedido_compra'),
                ('sap_pedido_compra_item', 'sap_pedido_compra_item'),
                ('sap_ordem_producao', 'sap_ordem_producao'),
                ('sap_ordem_producao_item', 'sap_ordem_producao_item'),
                ('sap_ordem_producao_componente', 'sap_ordem_producao_componente'),
                ('sap_reserva_item', 'sap_reserva_item'),
                ('sap_norma_embalagem', 'sap_norma_embalagem')
        ) AS t(nome_tabela, prefixo_coluna)
    LOOP
        coluna_criado := r.prefixo_coluna || '_criado_por';
        coluna_atualizado := r.prefixo_coluna || '_atualizado_por';
        coluna_excluido := r.prefixo_coluna || '_excluido_por';

        -- ====================================================
        -- FK: <tabela>_criado_por -> usuario(codigo_usuario)
        -- ====================================================
        IF EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = 'homologacao'
              AND table_name = r.nome_tabela
              AND column_name = coluna_criado
        ) THEN
            nome_constraint := 'fk_' || r.nome_tabela || '_criado_por';

            EXECUTE format(
                'ALTER TABLE homologacao.%I DROP CONSTRAINT IF EXISTS %I',
                r.nome_tabela,
                nome_constraint
            );

            EXECUTE format(
                'ALTER TABLE homologacao.%I
                 ADD CONSTRAINT %I
                 FOREIGN KEY (%I)
                 REFERENCES homologacao.usuario(codigo_usuario)
                 ON DELETE SET NULL',
                r.nome_tabela,
                nome_constraint,
                coluna_criado
            );
        END IF;

        -- ====================================================
        -- FK: <tabela>_atualizado_por -> usuario(codigo_usuario)
        -- ====================================================
        IF EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = 'homologacao'
              AND table_name = r.nome_tabela
              AND column_name = coluna_atualizado
        ) THEN
            nome_constraint := 'fk_' || r.nome_tabela || '_atualizado_por';

            EXECUTE format(
                'ALTER TABLE homologacao.%I DROP CONSTRAINT IF EXISTS %I',
                r.nome_tabela,
                nome_constraint
            );

            EXECUTE format(
                'ALTER TABLE homologacao.%I
                 ADD CONSTRAINT %I
                 FOREIGN KEY (%I)
                 REFERENCES homologacao.usuario(codigo_usuario)
                 ON DELETE SET NULL',
                r.nome_tabela,
                nome_constraint,
                coluna_atualizado
            );
        END IF;

        -- ====================================================
        -- FK de exclusão SOMENTE para log_alteracao_cadastral
        -- ====================================================
        IF r.nome_tabela = 'log_alteracao_cadastral'
           AND EXISTS (
                SELECT 1
                FROM information_schema.columns
                WHERE table_schema = 'homologacao'
                  AND table_name = r.nome_tabela
                  AND column_name = coluna_excluido
           )
        THEN
            nome_constraint := 'fk_' || r.nome_tabela || '_excluido_por';

            EXECUTE format(
                'ALTER TABLE homologacao.%I DROP CONSTRAINT IF EXISTS %I',
                r.nome_tabela,
                nome_constraint
            );

            EXECUTE format(
                'ALTER TABLE homologacao.%I
                 ADD CONSTRAINT %I
                 FOREIGN KEY (%I)
                 REFERENCES homologacao.usuario(codigo_usuario)
                 ON DELETE SET NULL',
                r.nome_tabela,
                nome_constraint,
                coluna_excluido
            );
        END IF;
    END LOOP;
END $$;

