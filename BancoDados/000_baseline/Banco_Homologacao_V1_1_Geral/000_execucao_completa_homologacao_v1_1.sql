CREATE OR REPLACE FUNCTION homologacao.limpar_log_integracao_sap(
    p_reter_dias integer DEFAULT 90
)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    v_excluidos integer;
BEGIN
    IF p_reter_dias < 30 THEN
        RAISE EXCEPTION 'A retencao minima permitida e de 30 dias.';
    END IF;

    DELETE FROM homologacao.log_integracao_sap
     WHERE registrado_em_utc < now() - make_interval(days => p_reter_dias);

    GET DIAGNOSTICS v_excluidos = ROW_COUNT;
    RETURN v_excluidos;
END;
$$;

