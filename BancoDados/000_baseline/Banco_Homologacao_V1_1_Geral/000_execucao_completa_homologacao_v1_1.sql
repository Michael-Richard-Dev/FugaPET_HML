-- ============================================================

CREATE OR REPLACE FUNCTION homologacao.fn_validar_hu_palete_possui_caixa()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status_hu_palete IN ('ENVIADO_SAP', 'CONFIRMADO_SAP') THEN
        IF NOT EXISTS (
            SELECT 1
            FROM homologacao.hu_palete_item hpi
            WHERE hpi.codigo_hu_palete = NEW.codigo_hu_palete
              AND hpi.situacao_hu_palete_item = true
              AND hpi.status_vinculo IN ('VINCULADO', 'ENVIADO_SAP', 'CONFIRMADO_SAP')
        ) THEN
            RAISE EXCEPTION 'HU Palete % não pode ficar com status % sem caixas vinculadas.',
                NEW.codigo_hu_palete,
                NEW.status_hu_palete;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_hu_palete_validar_caixas ON homologacao.hu_palete;

