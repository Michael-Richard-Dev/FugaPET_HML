CREATE OR REPLACE VIEW homologacao.vw_entrada_produto_item_resumo AS
SELECT
    epi.codigo_entrada_produto_item,
    epl.codigo_entrada_produto_lancamento,
    epl.numero_pedido,
    epi.numero_item,
    epi.material,
    epi.centro,
    epi.deposito,
    epi.unidade,
    epi.quantidade_prevista,
    epi.quantidade_recebida,
    epi.status_item,
    COUNT(epp.codigo_entrada_produto_pesagem) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ) AS quantidade_leituras_validas,
    COALESCE(SUM(epp.peso_bruto_kg) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ), 0)::numeric(14,3) AS peso_bruto_total_kg,
    COALESCE(SUM(epp.peso_tara_kg) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ), 0)::numeric(14,3) AS peso_tara_total_kg,
    COALESCE(SUM(epp.peso_liquido_kg) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ), 0)::numeric(14,3) AS peso_liquido_total_kg,
    MIN(epp.pesado_em) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ) AS primeira_pesagem_em,
    MAX(epp.pesado_em) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ) AS ultima_pesagem_em
FROM homologacao.entrada_produto_item epi
JOIN homologacao.entrada_produto_lancamento epl
    ON epl.codigo_entrada_produto_lancamento = epi.codigo_entrada_produto_lancamento
LEFT JOIN homologacao.entrada_produto_pesagem epp
    ON epp.codigo_entrada_produto_item = epi.codigo_entrada_produto_item
WHERE epi.situacao_entrada_produto_item = true
GROUP BY
    epi.codigo_entrada_produto_item,
    epl.codigo_entrada_produto_lancamento,
    epl.numero_pedido,
    epi.numero_item,
    epi.material,
    epi.centro,
    epi.deposito,
    epi.unidade,
    epi.quantidade_prevista,
    epi.quantidade_recebida,
    epi.status_item;

COMMENT ON VIEW homologacao.vw_entrada_produto_item_resumo IS
    'Resumo consolidado das leituras validas por item da Entrada de Produto.';

CREATE OR REPLACE VIEW homologacao.vw_entrada_produto_lancamento_resumo AS
SELECT
    epl.codigo_entrada_produto_lancamento,
    epl.numero_pedido,
    epl.fornecedor,
    epl.status_lancamento,
    epl.codigo_usuario,
    u.login_usuario,
    u.nome_usuario,
    epl.iniciado_em,
    epl.finalizado_em,
    COUNT(DISTINCT epi.codigo_entrada_produto_item) FILTER (
        WHERE epi.situacao_entrada_produto_item = true
    ) AS quantidade_itens,
    COUNT(epp.codigo_entrada_produto_pesagem) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ) AS quantidade_leituras_validas,
    COALESCE(SUM(epp.peso_bruto_kg) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ), 0)::numeric(14,3) AS peso_bruto_total_kg,
    COALESCE(SUM(epp.peso_tara_kg) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ), 0)::numeric(14,3) AS peso_tara_total_kg,
    COALESCE(SUM(epp.peso_liquido_kg) FILTER (
        WHERE epp.situacao_entrada_produto_pesagem = true
          AND epp.status_pesagem = 'VALIDA'
    ), 0)::numeric(14,3) AS peso_liquido_total_kg
FROM homologacao.entrada_produto_lancamento epl
LEFT JOIN homologacao.usuario u
    ON u.codigo_usuario = epl.codigo_usuario
LEFT JOIN homologacao.entrada_produto_item epi
    ON epi.codigo_entrada_produto_lancamento = epl.codigo_entrada_produto_lancamento
LEFT JOIN homologacao.entrada_produto_pesagem epp
    ON epp.codigo_entrada_produto_item = epi.codigo_entrada_produto_item
WHERE epl.situacao_entrada_produto_lancamento = true
GROUP BY
    epl.codigo_entrada_produto_lancamento,
    epl.numero_pedido,
    epl.fornecedor,
    epl.status_lancamento,
    epl.codigo_usuario,
    u.login_usuario,
    u.nome_usuario,
    epl.iniciado_em,
    epl.finalizado_em;

COMMENT ON VIEW homologacao.vw_entrada_produto_lancamento_resumo IS
    'Resumo consolidado dos lancamentos de Entrada de Produto.';

