-- ============================================================
-- Função padrão para atualizar coluna atualizado_em
-- ============================================================

CREATE OR REPLACE FUNCTION homologacao.fn_definir_atualizado_em()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_coluna_tabela text := TG_TABLE_NAME || '_atualizado_em';
BEGIN
    -- Padrão simples: atualizado_em
    --IF to_jsonb(NEW) ? 'atualizado_em' THEN
        --NEW.atualizado_em := date_trunc('minute', now());
    --END IF;

    -- Padrão por tabela: <tabela>_atualizado_em
    IF to_jsonb(NEW) ? v_coluna_tabela THEN
        NEW := jsonb_populate_record(
            NEW,
            jsonb_build_object(v_coluna_tabela, to_char(date_trunc('minute', now()), 'YYYY-MM-DD HH24:MI:SS'))
        );
    END IF;

    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION homologacao.fn_definir_atualizado_em()
IS 'Atualiza automaticamente atualizado_em ou <tabela>_atualizado_em antes de UPDATE.';

